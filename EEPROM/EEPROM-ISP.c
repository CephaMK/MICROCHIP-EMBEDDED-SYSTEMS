#include <xc.h>       // include processor files ? each processor file is guarded.
#define _XTAL_FREQ 20000000

unsigned int a;

// ?????????????????????????????????????????????
// SPI Write: send one byte via SSPBUF
// ????????????????????????????????????????????
void spi_write(unsigned int value)
{
    SSPBUF = value;
    while (!SSPSTATbits.BF);   // wait until transmission complete
    a = SSPBUF;                // read SSPBUF to clear BF flag
}

// ?????????????????????????????????????????????
// SPI Read: send dummy byte, return received byte
// ?????????????????????????????????????????????
unsigned char spi_read()
{
    SSPBUF = 0x00;             // initiate bus cycle (dummy write)
    while (!PIR1bits.SSPIF);   // wait until cycle complete
    PIR1bits.SSPIF = 0;        // clear interrupt flag
    return (SSPBUF);           // return byte read
}

// ?????????????????????????????????????????????
// Write one byte to 25AA160A EEPROM
// Address = (msb << 8) | lsb
// ?????????????????????????????????????????????
void write_to_25AA160A(unsigned char msb, unsigned char lsb, unsigned char data)
{
    PORTBbits.RB0 = 0;         // Slave Select LOW  (enable EEPROM)
        spi_write(0x02);       // WRITE command
        spi_write(msb);        // Address MSB
        spi_write(lsb);        // Address LSB
        spi_write(data);       // Data byte
    PORTBbits.RB0 = 1;         // Slave Select HIGH (disable EEPROM)
}

// ?????????????????????????????????????????????
// Read one byte from 25AA160A EEPROM
// Address = (msb << 8) | lsb
// Result stored in global variable 'a'
// ?????????????????????????????????????????????
void read_from_25AA160A(unsigned char msb, unsigned char lsb)
{
    PORTBbits.RB0 = 0;         // Slave Select LOW
        spi_write(0x03);       // READ command
        spi_write(msb);        // Address MSB
        spi_write(lsb);        // Address LSB
        while (!SSPSTATbits.BF);
        a = (spi_read());      // dummy write clocks in the data byte
    PORTBbits.RB0 = 1;         // Slave Select HIGH
}

// ?????????????????????????????????????????????
// MAIN
// ?????????????????????????????????????????????
void main()
{
    // ?? Pin Direction Setup ??
    TRISCbits.TRISC3 = 0;      // SCK  ? Serial Clock as OUTPUT
    TRISCbits.TRISC4 = 1;      // MISO ? Master In Slave Out as INPUT
    TRISCbits.TRISC5 = 0;      // MOSI ? Master Out Slave In as OUTPUT
    TRISBbits.TRISB0 = 0;      // SS   ? Slave Select pin as OUTPUT

    // ?? SPI Module Configuration ??
    SSPCON  = 0x20;            // 0b0010_0000 ? SPI Master, Fosc/4, CKP=0
    SSPSTAT = 0x00;            // CKE=0, SMP=0 (sample at middle of data output time)

    // ?? Step 1: Write Enable (WREN = 0x06) ??
    PORTBbits.RB0 = 0;         // Slave Select LOW
    spi_write(0x06);           // WREN command
    PORTBbits.RB0 = 1;         // Slave Select HIGH

    // ?? Step 2: Write 0x09 to address 0x0343 ??
    write_to_25AA160A(0x03, 0x43, 0x09);   // 0x0343 ? 0x09
    __delay_ms(1000);

    // ?? Step 3: Write Disable (WRDI = 0x04) ??
    PORTBbits.RB0 = 0;         // Slave Select LOW
    spi_write(0x04);           // WRDI command
    PORTBbits.RB0 = 1;         // Slave Select HIGH

    __delay_ms(1000);

    // ?? Step 4: Read back from address 0x0343 ??
    read_from_25AA160A(0x03, 0x43);   // result stored in 'a'

    while (1)
    {
        // Main loop ? do nothing (read value is in variable 'a')
    }

    return;
}